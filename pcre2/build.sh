#!/bin/bash
# Build PCRE2 for SLOW-32: the 8-bit library (out/libpcre2-8.s32a + pcre2.h),
# the POSIX wrapper (out/libpcre2-posix.s32a + pcre2posix.h) and PCRE2's own
# test driver (out/pcre2test.s32x), which run-tests.sh runs over PCRE2's
# test data.
#
# src/ is the pristine 10.49 release (src/ of pcre2-10.49.tar.bz2, sha256
# 53c156e1ba416a20da8e65395daa132da0d80e76910424caca3fcdae7831d384), built
# by hand as NON-AUTOTOOLS-BUILD describes: config.h.generic, pcre2.h.generic
# and pcre2_chartables.c.dist are copied into out/ rather than edited in
# place, with this machine's settings written ahead of config.h.generic's
# defaults.  8-bit code units with Unicode; no JIT (code is execute-only and
# nothing may write it), no 16/32-bit libraries.
set -e
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$SCRIPT_DIR/.."
TOOLCHAIN="$PROJECT_DIR/tools"
RUNTIME="$PROJECT_DIR/runtime"
SRC="$SCRIPT_DIR/src"
OUTDIR="$SCRIPT_DIR/out"
LLVM="${LLVM_BIN:-$HOME/llvm-project/build/bin}"
CLANG="$LLVM/clang"; LLC="$LLVM/llc"
S32ASM="${S32_AS:-$TOOLCHAIN/assembler/slow32asm}"
S32AR="${S32_AR:-$TOOLCHAIN/utilities/s32-ar}"
RTINC="${S32_RT_INCLUDE:-$RUNTIME/include}"
mkdir -p "$OUTDIR/inc"

{
    echo "/* SLOW-32 settings, ahead of config.h.generic (generated by build.sh) */"
    for d in SUPPORT_PCRE2_8 SUPPORT_UNICODE HAVE_ASSERT_H HAVE_INTTYPES_H \
             HAVE_LIMITS_H HAVE_STDINT_H HAVE_STDIO_H HAVE_STDLIB_H HAVE_STRING_H \
             HAVE_STRINGS_H HAVE_SYS_STAT_H HAVE_SYS_TYPES_H HAVE_UNISTD_H \
             HAVE_BUILTIN_MUL_OVERFLOW HAVE_BUILTIN_UNREACHABLE; do
        echo "#define $d 1"
    done
    cat "$SRC/config.h.generic"
} > "$OUTDIR/inc/config.h"
cp "$SRC/pcre2.h.generic" "$OUTDIR/inc/pcre2.h"
cp "$SRC/pcre2_chartables.c.dist" "$OUTDIR/pcre2_chartables.c"

CFLAGS="-target slow32-unknown-none -S -emit-llvm -O2 -I$RTINC -I$OUTDIR/inc -I$SRC
        -DHAVE_CONFIG_H -DPCRE2_STATIC"

cc1() {   # cc1 file.c [cflags...] -> out/file.s32o
    local src="$1"; shift
    local b="$(basename "$src" .c)"
    echo "  $b.c"
    # by bare name from its own directory, so __FILE__ in an assert names
    # the file and not this machine's build path
    (cd "$(dirname "$src")" && $CLANG $CFLAGS "$@" "$(basename "$src")" -o "$OUTDIR/$b.ll")
    $LLC -mtriple=slow32-unknown-none "$OUTDIR/$b.ll" -o "$OUTDIR/$b.s"
    "$S32ASM" "$OUTDIR/$b.s" "$OUTDIR/$b.s32o" > /dev/null
}

LIB8="auto_possess chkdint compile compile_cgroup compile_class config context
      convert dfa_match error extuni find_bracket jit_compile maketables match
      match_data match_next newline ord2utf pattern_info script_run serialize
      string_utils study substitute substring tables ucd valid_utf xclass"

echo "=== libpcre2-8"
objs=()
for m in $LIB8; do
    cc1 "$SRC/pcre2_$m.c" -DPCRE2_CODE_UNIT_WIDTH=8
    objs+=("$OUTDIR/pcre2_$m.s32o")
done
cc1 "$OUTDIR/pcre2_chartables.c" -DPCRE2_CODE_UNIT_WIDTH=8
objs+=("$OUTDIR/pcre2_chartables.s32o")
rm -f "$OUTDIR/libpcre2-8.s32a"
"$S32AR" rc "$OUTDIR/libpcre2-8.s32a" "${objs[@]}"
cp "$OUTDIR/inc/pcre2.h" "$OUTDIR/pcre2.h"

echo "=== libpcre2-posix"
cc1 "$SRC/pcre2posix.c" -DPCRE2_CODE_UNIT_WIDTH=8
rm -f "$OUTDIR/libpcre2-posix.s32a"
"$S32AR" rc "$OUTDIR/libpcre2-posix.s32a" "$OUTDIR/pcre2posix.s32o"
cp "$SRC/pcre2posix.h" "$OUTDIR/pcre2posix.h"
echo "  -> $OUTDIR/libpcre2-8.s32a, libpcre2-posix.s32a, pcre2.h, pcre2posix.h"
[ -n "${PCRE2_LIB_ONLY:-}" ] && exit 0

echo "=== pcre2test"
cc1 "$SRC/pcre2test.c"
"$TOOLCHAIN/linker/s32-ld" --mmio 64K --code-size 2M --stack-size 1M --heap-size 64M \
    -o "$OUTDIR/pcre2test.s32x" "$RUNTIME/crt0.s32o" "$OUTDIR/pcre2test.s32o" \
    "$OUTDIR/libpcre2-posix.s32a" "$OUTDIR/libpcre2-8.s32a" \
    "$RUNTIME/libc_mmio.s32a" "$RUNTIME/libs32.s32a"
echo "  -> $OUTDIR/pcre2test.s32x"
