#!/usr/bin/env python3
"""Generate the glue between musl's libm (musl/, verbatim) and SLOW-32.

    python3 runtime/libm/gen.py        (from anywhere; rerun after an update)

Writes, beside this script:
  sources.txt  the musl files both libraries build (see SKIP below)
  complex_sources.txt  the <complex.h> files (musl/src/complex), all of them
  rename.h     each C11 function musl defines, renamed __musl_<name>; the
               build compiles every musl file behind it (compat.h), so
               musl's functions -- and its calls between them -- carry no
               errno handling
  errno.c      the public functions: each calls __musl_<name> and sets
               errno as math_errhandling == MATH_ERRNO asks (7.12.1):
               EDOM when a NaN comes back from arguments that are not NaN
               (a domain error), ERANGE when an infinity comes back from
               finite ones (a pole error or overflow).  Underflow sets
               nothing (7.12.1p6 leaves it to the implementation).
The prototypes come from runtime/include/math.h.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MATH = os.path.join(HERE, 'musl', 'src', 'math')
COMPLEX = os.path.join(HERE, 'musl', 'src', 'complex')
HDR = os.path.join(HERE, '..', 'include', 'math.h')

# musl's square roots are software; SLOW-32 has FSQRT (math_hw.c, which
# both libraries build, sets EDOM itself).  sqrt_data.c is their table.
SKIP = {'sqrt.c', 'sqrtf.c', 'sqrt_data.c'}
# Implemented by the hardware where a library has it: left out of the
# clang runtime's list only (runtime/Makefile), not renamed anywhere.
HW_ONLY = {'sqrt', 'sqrtf', 'fabs', 'fabsf'}
FLOAT_TYPES = ('double', 'float', 'long double')


def prototypes():
    protos = []
    for line in open(HDR):
        m = re.match(r'^(double|float|long double|int|long|long long) ([a-z_0-9]+)\((.*)\);$', line.strip())
        if m and not m.group(2).startswith('__'):
            protos.append((m.group(1), m.group(2), [p.strip() for p in m.group(3).split(',')]))
    return protos


def musl_defines():
    names = set()
    for f in os.listdir(MATH):
        if not f.endswith('.c') or f in SKIP:
            continue
        for line in open(os.path.join(MATH, f), errors='replace'):
            m = re.match(r'^(?:double|float|long double|int|long|long long)\s+([a-z_0-9]+)\(', line)
            if m:
                names.add(m.group(1))
    return names


def main():
    protos = prototypes()
    defined = musl_defines()
    srcs = sorted(f for f in os.listdir(MATH) if f.endswith('.c') and f not in SKIP)
    with open(os.path.join(HERE, 'sources.txt'), 'w') as o:
        o.write(''.join(f + '\n' for f in srcs))
    csrcs = sorted(f for f in os.listdir(COMPLEX) if f.endswith('.c'))
    with open(os.path.join(HERE, 'complex_sources.txt'), 'w') as o:
        o.write(''.join(f + '\n' for f in csrcs))

    wrapped = []
    for ret, name, params in protos:
        if name in HW_ONLY or name not in defined:
            continue
        wrapped.append((ret, name, params))

    with open(os.path.join(HERE, 'rename.h'), 'w') as o:
        o.write('/* Generated by gen.py: musl\'s C11 functions under internal names. */\n')
        for _, name, _ in wrapped:
            o.write('#define %s __musl_%s\n' % (name, name))

    with open(os.path.join(HERE, 'errno.c'), 'w') as o:
        o.write('''/* Generated by gen.py.  The C11 <math.h> functions: musl's (runtime/libm,
 * MIT), with errno set as math_errhandling == MATH_ERRNO asks -- EDOM for
 * a NaN from arguments that are not NaN, ERANGE for an infinity from finite
 * ones.  musl itself reports errors through exception flags, which
 * SLOW-32 does not have. */
#include <errno.h>
#include <math.h>

static void s32_merr(double r, int nan_in, int all_finite) {
    if (isnan(r)) {
        if (!nan_in) errno = EDOM;
    } else if (isinf(r) && all_finite) {
        errno = ERANGE;
    }
}

''')
        for ret, name, params in wrapped:
            decl, args, fl = [], [], []
            for i, p in enumerate(params):
                if p == 'void':
                    continue
                a = 'a%d' % i
                if p.endswith('*'):
                    decl.append('%s%s' % (p, a))
                else:
                    decl.append('%s %s' % (p, a))
                args.append(a)
                if p in FLOAT_TYPES:
                    fl.append(a)
            o.write('%s __musl_%s(%s);\n' % (ret, name, ', '.join(params)))
            if ret in FLOAT_TYPES and fl:
                nan_in = ' || '.join('isnan(%s)' % a for a in fl)
                fin = ' && '.join('isfinite(%s)' % a for a in fl)
                o.write('%s %s(%s) {\n    %s r = __musl_%s(%s);\n    s32_merr(r, %s, %s);\n    return r;\n}\n\n'
                        % (ret, name, ', '.join(decl), ret, name, ', '.join(args), nan_in, fin))
            else:
                o.write('%s %s(%s) {\n    return __musl_%s(%s);\n}\n\n'
                        % (ret, name, ', '.join(decl) or 'void', name, ', '.join(args)))
    print('%d sources, %d complex sources, %d functions wrapped' % (len(srcs), len(csrcs), len(wrapped)))


main()
