"""Generate the embeddable C tables from gen/resolved.json.

Emits gen/tz_data.h containing:
  - TZ_ZONES[]      index -> IANA id string (index 0 = "" unknown)
  - TZ_ZIP_ZONE[]   100000-byte direct map: zip (0..99999) -> zone index
  - TZ_NPA_ZONE[]   1000-byte direct map:   NPA (0..999)   -> zone index

A 5-digit ZIP and a 3-digit NPA are already perfect hashes into these arrays,
so lookup is a single O(1) array load. The whole thing is ~101 KB of static
data, baked into the binary.
"""

import json
import sys
import textwrap

from sources import GEN

ZIP_N = 100000
NPA_N = 1000


def emit_byte_array(name, data, out):
    out.write(f"static const unsigned char {name}[{len(data)}] = {{\n")
    # 24 values per line keeps the file readable and diff-friendly.
    for i in range(0, len(data), 24):
        chunk = ",".join(str(b) for b in data[i:i + 24])
        out.write(f"  {chunk},\n")
    out.write("};\n\n")


def main() -> int:
    with open(GEN / "resolved.json") as f:
        r = json.load(f)

    zones = r["zones"]                 # index i -> zone, stored at table slot i+1
    if len(zones) > 254:
        raise SystemExit(f"too many zones ({len(zones)}) for uint8 table")

    zip_arr = bytearray(ZIP_N)
    for z, idx in r["zip_to_idx"].items():
        zip_arr[int(z)] = idx
    npa_arr = bytearray(NPA_N)
    for n, idx in r["npa_to_idx"].items():
        npa_arr[int(n)] = idx

    out_path = GEN / "tz_data.h"
    with open(out_path, "w") as out:
        out.write("/* Generated by build/emit_c.py -- do not edit. */\n")
        out.write("#ifndef TZ_DATA_H\n#define TZ_DATA_H\n\n")
        out.write(f"#define TZ_ZONE_COUNT {len(zones) + 1}\n")
        out.write(f"#define TZ_ZIP_MAX {ZIP_N}\n")
        out.write(f"#define TZ_NPA_MAX {NPA_N}\n\n")

        out.write("static const char *const TZ_ZONES[] = {\n  \"\",\n")
        for name in zones:
            out.write(f"  \"{name}\",\n")
        out.write("};\n\n")

        emit_byte_array("TZ_ZIP_ZONE", zip_arr, out)
        emit_byte_array("TZ_NPA_ZONE", npa_arr, out)
        out.write("#endif /* TZ_DATA_H */\n")

    nz = sum(1 for b in zip_arr if b)
    nn = sum(1 for b in npa_arr if b)
    print(f"wrote {out_path.name}: {len(zones)} zones, "
          f"{nz} ZIPs, {nn} area codes, {out_path.stat().st_size:,} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
