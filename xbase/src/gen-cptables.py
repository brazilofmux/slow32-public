#!/usr/bin/env python3
"""Write cptables.h: the code points of bytes 0x80-0xFF in CP850 (the PC's
multilingual codepage, most of the dBASE and Clipper world outside the US)
and Windows 1252 (FoxPro for Windows' tables), as Python's codecs have them
-- Unicode's MICSFT mappings.  1252 leaves 0x81 0x8D 0x8F 0x90 0x9D
unassigned; they are taken as the C1 controls of the same number, as
Windows' MultiByteToWideChar does.  CP437 is common/s32cp437.h.
    python3 xbase/src/gen-cptables.py > xbase/src/cptables.h"""
import sys

def high(cp):
    out = []
    for b in range(128, 256):
        try:
            out.append(ord(bytes([b]).decode(cp)))
        except UnicodeDecodeError:
            out.append(b)
    return out

def table(name, vals):
    rows = ['    ' + ', '.join('0x%04X' % v for v in vals[i:i + 8]) + ',  /* 0x%02X */' % (128 + i)
            for i in range(0, 128, 8)]
    return 'static const unsigned short %s[128] = {\n%s\n};\n' % (name, '\n'.join(rows))

sys.stdout.write('/* Generated by gen-cptables.py -- do not edit. */\n'
                 '#ifndef XBASE_CPTABLES_H\n#define XBASE_CPTABLES_H\n\n'
                 + table('cp850_hi', high('cp850')) + '\n'
                 + table('cp1252_hi', high('cp1252')) + '\n#endif\n')
