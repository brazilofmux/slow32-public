#!/usr/bin/env python3
"""gen-limits.py -- write the 5.2.4.1 translation-limit probes.

C11 5.2.4.1 lists the least a conforming implementation must translate
and execute: one program containing at least one instance of every
limit.  Each probe here takes one limit at exactly its minimum, so a
compiler with a fixed table smaller than the standard asks for fails
it.  Written by script because several are thousands of lines.

    ./gen-limits.py          # (re)write probes/5.2.4.1-*.c
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'probes')


def probe(slug, line1, body):
    path = os.path.join(OUT, '5.2.4.1-%s.c' % slug)
    with open(path, 'w', newline='\n') as f:
        f.write('// 5.2.4.1  %s\n' % line1)
        f.write('// (generated by gen-limits.py)\n')
        f.write(body)


def main_printing(expr, decls=''):
    return ('#include <stdio.h>\n' + decls +
            'int main(void) {\n    printf("%%d\\n", %s);\n    return 0;\n}\n' % expr)


# 127 nesting levels of blocks
n = 127
body = '#include <stdio.h>\nint main(void) {\n    int depth = 0;\n'
body += ''.join('{ depth = depth + 1;\n' for _ in range(n - 1))
body += 'printf("%d\\n", depth);\n' + '}\n' * (n - 1) + '    return 0;\n}\n'
probe('blocks-127', '127 nesting levels of blocks', body)

# 63 nesting levels of conditional inclusion
n = 63
body = '#include <stdio.h>\n#define LEVEL 0\n'
for i in range(n):
    body += '#if %d < 100\n' % i
body += '#undef LEVEL\n#define LEVEL %d\n' % n
body += '#endif\n' * n
body += 'int main(void) {\n    printf("%d\\n", LEVEL);\n    return 0;\n}\n'
probe('if-nesting-63', '63 nesting levels of conditional inclusion', body)

# 12 pointer, array, and function declarators modifying a type
body = ('#include <stdio.h>\n'
        'int main(void) {\n'
        '    int v = 7;\n'
        '    int *p1 = &v, **p2 = &p1, ***p3 = &p2, ****p4 = &p3, *****p5 = &p4;\n'
        '    int ******p6 = &p5, *******p7 = &p6, ********p8 = &p7;\n'
        '    int *********p9 = &p8, **********p10 = &p9, ***********p11 = &p10;\n'
        '    int ************p12 = &p11;\n'
        '    printf("%d\\n", ************p12);\n'
        '    return 0;\n}\n')
probe('declarators-12', '12 pointer declarators modifying one type', body)

# 63 nesting levels of parenthesized declarators within a full declarator
n = 63
body = ('#include <stdio.h>\n'
        'int ' + '(' * n + 'deep' + ')' * n + ' = 63;\n'
        'int main(void) {\n    printf("%d\\n", deep);\n    return 0;\n}\n')
probe('paren-declarator-63', '63 nesting levels of parenthesized declarators', body)

# 63 nesting levels of parenthesized expressions within a full expression
n = 63
probe('paren-expr-63', '63 nesting levels of parenthesized expressions',
      main_printing('(' * n + '21 * 3' + ')' * n))

# 63 significant initial characters in an internal identifier
stem = 'i' * 62
probe('internal-ident-63', '63 significant initial characters in an internal identifier',
      main_printing('%sa * 10 + %sb' % (stem, stem),
                    'static int %sa = 4;\nstatic int %sb = 2;\n' % (stem, stem)))

# 31 significant initial characters in an external identifier
stem = 'x' * 30
probe('external-ident-31', '31 significant initial characters in an external identifier',
      main_printing('%sa * 10 + %sb' % (stem, stem),
                    'int %sa = 3;\nint %sb = 1;\n' % (stem, stem)))

# 4095 external identifiers in one translation unit
n = 4095
decls = ''.join('int e%04d = %d;\n' % (i, i % 7) for i in range(n))
probe('external-idents-4095', '4095 external identifiers in one translation unit',
      main_printing('e0000 + e4094 + e2047', decls))

# 511 identifiers with block scope declared in one block
n = 511
body = '#include <stdio.h>\nint main(void) {\n'
body += ''.join('    int b%03d = %d;\n' % (i, i % 5) for i in range(n))
body += '    printf("%d\\n", b000 + b255 + b510);\n    return 0;\n}\n'
probe('block-idents-511', '511 identifiers with block scope in one block', body)

# 4095 macro identifiers simultaneously defined in one preprocessing unit
n = 4095
decls = ''.join('#define M%04d %d\n' % (i, i % 9) for i in range(n))
probe('macros-4095', '4095 macro identifiers defined at once',
      main_printing('M0000 + M4094 + M2048', decls))

# 127 parameters in one function definition; 127 arguments in one call
n = 127
params = ', '.join('int p%03d' % i for i in range(n))
args = ', '.join(str(i % 3) for i in range(n))
decls = ('static int sum127(%s) {\n    return p000 + p063 + p126 + %s;\n}\n'
         % (params, ' + '.join('p%03d' % i for i in range(n))))
probe('params-127', '127 parameters in one definition, 127 arguments in one call',
      main_printing('sum127(%s)' % args, decls))

# 127 parameters in one macro definition; 127 arguments in one invocation
n = 127
mparams = ', '.join('a%03d' % i for i in range(n))
margs = ', '.join(str(i % 4) for i in range(n))
decls = '#define PICK(%s) (a000 + a064 + a126)\n' % mparams
probe('macro-params-127', '127 parameters in one macro, 127 arguments in one invocation',
      main_printing('PICK(%s)' % margs, decls))

# 4095 characters in a logical source line
expr = ' + '.join(['1'] * 1000)          # 1000*4-3 = 3997 characters
line = 'int sum = %s' % expr
line = line + ' ' * (4095 - len(line) - 1) + ';'      # padded inside the declaration
assert len(line) == 4095
body = '#include <stdio.h>\n%s\nint main(void) {\n    printf("%%d\\n", sum);\n    return 0;\n}\n' % line
probe('logical-line-4095', '4095 characters in a logical source line', body)

# 4095 characters in a string literal (after concatenation)
chunk = 'abcdefghijklmnopqrstuvwxyz0123456789' * 3      # 108
pieces = []
total = 0
while total + len(chunk) <= 4095:
    pieces.append(chunk)
    total += len(chunk)
pieces.append('Z' * (4095 - total))
body = ('#include <stdio.h>\n#include <string.h>\n'
        'static const char s[] =\n' + ''.join('    "%s"\n' % p for p in pieces) + ';\n'
        'int main(void) {\n    printf("%d %c\\n", (int)strlen(s), s[4094]);\n    return 0;\n}\n')
probe('string-4095', '4095 characters in a string literal', body)

# 65535 bytes in an object
body = ('#include <stdio.h>\n'
        'static unsigned char big[65535];\n'
        'int main(void) {\n'
        '    big[0] = 1; big[65534] = 2;\n'
        '    printf("%d %d\\n", (int)sizeof big, big[0] + big[65534]);\n'
        '    return 0;\n}\n')
probe('object-65535', '65535 bytes in an object', body)

# 15 nesting levels for #included files: the probe includes itself
levels = 15
body = ''
for i in range(1, levels + 1):
    kw = '#if' if i == 1 else '#elif'
    body += '%s !defined INC%d\n#define INC%d\n' % (kw, i, i)
    body += '#define DEPTH %d\n' % i if i == 1 else '#undef DEPTH\n#define DEPTH %d\n' % i
    if i < levels:
        body += '#include "5.2.4.1-include-nesting-15.c"\n'   # itself, by its own name
body += '#endif\n'
body += ('#ifndef PROBE_MAIN\n#define PROBE_MAIN\n#include <stdio.h>\n'
         'int main(void) {\n    printf("%d\\n", DEPTH);\n    return 0;\n}\n#endif\n')
probe('include-nesting-15', '15 nesting levels for #included files', body)

# 1023 case labels for a switch statement
n = 1023
body = '#include <stdio.h>\nstatic int f(int k) {\n    switch (k) {\n'
body += ''.join('    case %d: return %d;\n' % (i, i * 2) for i in range(n))
body += '    }\n    return -1;\n}\n'
body += 'int main(void) {\n    printf("%d %d %d\\n", f(0), f(1022), f(1023));\n    return 0;\n}\n'
probe('case-labels-1023', '1023 case labels in one switch', body)

# 1023 members in a single structure
n = 1023
body = '#include <stdio.h>\nstruct wide {\n' + ''.join('    int m%04d;\n' % i for i in range(n)) + '};\n'
body += ('int main(void) {\n    static struct wide w;\n    w.m0000 = 1; w.m1022 = 2;\n'
         '    printf("%d %d\\n", (int)(sizeof w / sizeof w.m0000), w.m0000 + w.m1022);\n'
         '    return 0;\n}\n')
probe('members-1023', '1023 members in one structure', body)

# 1023 enumeration constants in a single enumeration
n = 1023
body = '#include <stdio.h>\nenum many {\n' + ''.join('    E%04d,\n' % i for i in range(n)) + '};\n'
body += 'int main(void) {\n    printf("%d %d\\n", (int)E0000, (int)E1022);\n    return 0;\n}\n'
probe('enum-1023', '1023 enumeration constants in one enumeration', body)

# 63 levels of nested structure or union definitions
n = 63
body = '#include <stdio.h>\n'
body += ''.join('struct s%02d { int v%02d;\n' % (i, i) for i in range(n))
body += ''.join('} f%02d;\n' % (n - 1 - i) if i < n - 1 else '};\n' for i in range(n))
body += ('int main(void) {\n    struct s00 x;\n    x.v00 = 5;\n    x.f01.f02.f03.v03 = 6;\n'
         '    printf("%d\\n", x.v00 + x.f01.f02.f03.v03);\n    return 0;\n}\n')
probe('nested-structs-63', '63 levels of nested structure definitions', body)

print('wrote', len([f for f in os.listdir(OUT) if f.startswith('5.2.4.1-')]), 'probes')
