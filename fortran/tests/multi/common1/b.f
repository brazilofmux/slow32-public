      SUBROUTINE XB(SRNAME, INFO)
      CHARACTER*(*) SRNAME
      INTEGER INFO
      INTEGER INFOT, NOUT
      LOGICAL OK, LERR
      CHARACTER*32 SRNAMT
      COMMON /INFOC/ INFOT, NOUT, OK, LERR
      COMMON /SRNAMC/ SRNAMT
      REAL Y(4)
      COMMON Y
      LERR = .TRUE.
      IF (INFO .NE. INFOT) OK = .FALSE.
      IF (SRNAME .NE. SRNAMT) OK = .FALSE.
      WRITE (NOUT, '(A, I3, L2, F6.2)') SRNAMT(1:LEN_TRIM(SRNAMT)),
     $   INFOT, LERR, Y(3)
      END
      BLOCK DATA BD
      INTEGER IV(3)
      DOUBLE PRECISION D
      COMMON /INIT/ D, IV
      DATA IV /1, 2, 3/, D /4.5D0/
      END
