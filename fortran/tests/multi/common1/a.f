C     COMMON ACROSS FILES: THE BLOCKS ARE ONE OBJECT FOR THE PROGRAM,
C     WHATEVER FILES NAME THEM (LAPACK'S TESTING XERBLA READS INFOT AND
C     SRNAMT IN /INFOC/ AND /SRNAMC/, SET BY ITS CALLERS ELSEWHERE).  A
C     BLOCK DATA IN ANOTHER FILE INITIALIZES /INIT/; BLANK COMMON TOO.
      PROGRAM MAIN1
      INTEGER INFOT, NOUT
      LOGICAL OK, LERR
      CHARACTER*32 SRNAMT
      COMMON /INFOC/ INFOT, NOUT, OK, LERR
      COMMON /SRNAMC/ SRNAMT
      INTEGER IV(3)
      DOUBLE PRECISION D
      COMMON /INIT/ D, IV
      REAL X(4)
      COMMON X
      INFOT = 7
      NOUT = 6
      OK = .TRUE.
      SRNAMT = 'SGGGLM'
      X(3) = 2.5
      CALL XB('SGGGLM', 7)
      WRITE (*, '(L2, 3I4, F6.2, F6.2)') OK, IV, D, X(3)
      END
