C     A PARAMETER AS THE UNIT OF OPEN AND CLOSE, BY ITS BARE NAME, AFTER
C     AN EXPRESSION OF ANOTHER TYPE: THE UNIT TOOK THE TYPE THE LAST
C     EXPRESSION LEFT, SO AFTER READ (NU, FMT='(A8)') CLOSE (NU) WAS
C     REFUSED ("CHARACTER VALUE WHERE A NUMERIC ONE IS NEEDED").  FOUND
C     COMPILING LAPACK'S TESTING/LIN/DCHKAB.F.
      PROGRAM CLOSP1
      INTEGER NU
      PARAMETER (NU = 11)
      CHARACTER*8 LINE
      OPEN (NU, FILE='clp1.tmp')
      WRITE (NU, FMT='(A8)') 'ABCDEFGH'
      CLOSE (NU)
      OPEN (NU, FILE='clp1.tmp', STATUS='OLD')
      READ (NU, FMT='(A8)') LINE
      CLOSE (NU, STATUS='DELETE')
      WRITE (*, '(1X,A)') LINE
      END
