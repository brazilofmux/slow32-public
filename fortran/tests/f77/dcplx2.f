C     COMPLEX*16 IN COMMON, EQUIVALENCE, DATA, PARAMETER AND IMPLICIT,
C     AND COMPLEX CONSTANTS WITH A DOUBLE PRECISION PART: THOSE ARE
C     COMPLEX*16, EACH PART AS ITS OWN TYPE MAKES IT -- (0.1D0, 0.2) IS
C     THE DOUBLE 0.1 AND THE SINGLE 0.2 WIDENED, AS GFORTRAN HAS IT.
      PROGRAM DCPLX2
      IMPLICIT DOUBLE COMPLEX (Z)
      COMPLEX*16 C(2), P
      DOUBLE PRECISION D(4)
      COMMON /BLK/ C, ZB
      EQUIVALENCE (P, D(1))
      PARAMETER (ZK = (1.5D0, -0.5D0))
      DATA ZD /(2.0D0, 3.0D0)/
      COMPLEX*16 ZE(2)
      DATA ZE /(1.0, 2.0), (3.0D0, 4.0D0)/
      C(1) = DCMPLX(1.0D0, 2.0D0)
      C(2) = DCMPLX(3.0D0, 4.0D0)
      ZB = C(2)
      CALL SHOW
      P = DCMPLX(5.0D0, 6.0D0)
      WRITE (*, 100) D(1), D(2)
      WRITE (*, 100) DREAL(ZK), DIMAG(ZK)
      WRITE (*, 100) DREAL(ZD), DIMAG(ZD)
      WRITE (*, 100) DREAL(ZE(1)), DIMAG(ZE(2))
      ZA = (0.25D0, 0.125D0)
      WRITE (*, 100) DREAL(ZA), DIMAG(ZA)
  100 FORMAT (2F22.15)
      END
      SUBROUTINE SHOW
      COMPLEX*16 C(2), ZB
      COMMON /BLK/ C, ZB
      WRITE (*, 100) DREAL(C(1)), DIMAG(C(2)), DREAL(ZB)
  100 FORMAT (3F22.15)
      END
