C     FORTRAN 90 TRANSFER AS AN ACTUAL ARGUMENT: A DOUBLE PRECISION
C     SECTION AS COMPLEX*16 (LAPACK'S XYYRFSX), BESIDE THE ARRAY ITSELF:
C     THE CALLEE'S STORES REACH A COPY, NOT W.  A WHOLE ARRAY, A STRIDED
C     SECTION, A SCALAR AND AN ELEMENT, AN ARRAY MOLD AND A SCALAR ONE,
C     REAL AS COMPLEX, AND TRANSFER IN A FUNCTION REFERENCE.
      PROGRAM F90XF1
      DOUBLE PRECISION W(8), ZERO
      PARAMETER (ZERO = 0.0D0)
      REAL R(6), RZ
      PARAMETER (RZ = 0.0)
      INTEGER I, K(4), ISUM
      DO 10 I = 1, 8
        W(I) = I
   10 CONTINUE
      CALL ZTAIL(4, W, TRANSFER(W(1:8), (/ (ZERO, ZERO) /), 4))
      WRITE (*, 100) W
      CALL ZTAIL(2, W(5), TRANSFER(W(1:7:2), (/ (ZERO, ZERO) /)))
      WRITE (*, 100) W
      DO 20 I = 1, 6
        R(I) = 0.5 * I
   20 CONTINUE
      CALL CSHOW(3, TRANSFER(R, (/ (RZ, RZ) /), 3))
      CALL ISHOW1(TRANSFER(1.0, 0))
      CALL ISHOW1(TRANSFER(R(2), I))
      CALL ISHOW(4, TRANSFER(R(1:4), K))
      WRITE (*, 200) ISUM(4, TRANSFER(R(3:6), K, 4))
  100 FORMAT (1X, 8F7.2)
  200 FORMAT (1X, I12)
      END

      SUBROUTINE ZTAIL(N, A, Y)
      INTEGER N, I
      DOUBLE PRECISION A(N)
      COMPLEX*16 Y(N)
      DO 10 I = 1, N
        WRITE (*, 100) I, Y(I), A(I)
        Y(I) = (99D0, 99D0)
   10 CONTINUE
  100 FORMAT (1X, I2, 3F8.2)
      END

      SUBROUTINE CSHOW(N, C)
      INTEGER N, I
      COMPLEX C(N)
      WRITE (*, 100) (C(I), I = 1, N)
  100 FORMAT (1X, 6F6.2)
      END

      SUBROUTINE ISHOW(N, K)
      INTEGER N, K(N), I
      WRITE (*, 100) (K(I), I = 1, N)
  100 FORMAT (1X, 4I12)
      END

      SUBROUTINE ISHOW1(K)
      INTEGER K
      WRITE (*, 100) K
  100 FORMAT (1X, I12)
      END

      INTEGER FUNCTION ISUM(N, K)
      INTEGER N, K(N), I
      ISUM = 0
      DO 10 I = 1, N
        ISUM = ISUM + K(I) / 1024
   10 CONTINUE
      END
