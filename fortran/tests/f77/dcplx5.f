C     COMPLEX*16 I/O AND INTRINSICS: FORMATTED (EACH PART TAKES AN EDIT
C     DESCRIPTOR), LIST-DIRECTED (GFORTRAN'S 53-COLUMN PAIR), INTERNAL
C     READ BOTH WAYS (BLANKS INSIDE THE PARENTHESES), UNFORMATTED, NAMELIST
C     WRITE THEN READ; SQRT EXP LOG SIN COS AND THE CD/Z NAMES, PRINTED TO
C     12 DIGITS (GFORTRAN USES THE HOST'S COMPLEX LIBM).
      PROGRAM DCPLX5
      COMPLEX*16 A, B, C(2), Z
      CHARACTER*80 LINE
      NAMELIST /NL/ A
      A = (1.25D0, -2.5D0)
      WRITE (*, 100) A
      WRITE (*, 110) A
      WRITE (*, 120) A, 7
      PRINT *, A
      PRINT *, A, (0.5D0, 0.0D0)
      LINE = '  3.5  -4.25'
      READ (LINE, 130) B
      WRITE (*, 100) B
      LINE = '(1.5, 2.5) (3.0,-1.0)'
      READ (LINE, *) C
      WRITE (*, 100) C(1), C(2)
      OPEN (UNIT=9, FILE='dc5.tmp', FORM='UNFORMATTED')
      WRITE (9) A, C(2)
      REWIND 9
      READ (9) Z, B
      CLOSE (9, STATUS='DELETE')
      WRITE (*, 100) Z, B
      OPEN (UNIT=8, FILE='dc5n.tmp', STATUS='UNKNOWN')
      WRITE (8, NL)
      A = (0.0D0, 0.0D0)
      REWIND 8
      READ (8, NL)
      CLOSE (8, STATUS='DELETE')
      WRITE (*, 100) A
      Z = (2.0D0, 1.0D0)
      WRITE (*, 140) SQRT(Z), CDSQRT((-4.0D0, 0.0D0))
      WRITE (*, 140) EXP(Z), CDEXP((0.0D0, 0.0D0))
      WRITE (*, 140) LOG(Z), ZLOG((1.0D0, 0.0D0))
      WRITE (*, 140) SIN(Z), COS(Z)
  100 FORMAT (2F14.6)
  110 FORMAT (2E16.7)
  120 FORMAT (D24.15, D24.15, I4)
  130 FORMAT (2F6.2)
  140 FORMAT (4F18.12)
      END
