C     FORTRAN 90 ALLOCATABLE ARRAYS: ALLOCATE WITH AND WITHOUT LOWER BOUNDS
C     AND STAT=, ELEMENTS, A WHOLE ONE AS AN ACTUAL ARGUMENT AND IN AN I/O
C     LIST, A SECTION ASSIGNED, MAXLOC/MAXVAL, ALLOCATED, ALLOCATE OF ONE
C     ALLOCATED AND DEALLOCATE OF ONE NOT (GFORTRAN'S STAT VALUES), A NEW
C     SHAPE AFTER DEALLOCATE, AND A SUBROUTINE'S FREED AT EACH RETURN.
      PROGRAM F90AL1
      DOUBLE PRECISION, ALLOCATABLE :: A(:,:), W(:)
      INTEGER, ALLOCATABLE :: IW(:)
      INTEGER I, J, M, N, IST
      M = 3
      N = 4
      ALLOCATE (A(M,N), W(0:5))
      ALLOCATE (IW(-2:2), STAT=IST)
      WRITE (*, 100) IST, ALLOCATED(A), ALLOCATED(IW)
      DO 10 J = 1, N
      DO 10 I = 1, M
        A(I,J) = 10 * I + J
   10 CONTINUE
      DO 20 I = 0, 5
        W(I) = DBLE(I) * 0.5D0
   20 CONTINUE
      DO 30 I = -2, 2
        IW(I) = I * I
   30 CONTINUE
      CALL SHOW(A, M, N)
      W(1:3) = -1.0D0
      WRITE (*, 200) W
      WRITE (*, 300) IW, MAXLOC(IW, 1), MAXVAL(IW(-1:1))
      ALLOCATE (A(2,2), STAT=IST)
      WRITE (*, 300) IST
      DEALLOCATE (A, W)
      DEALLOCATE (W, STAT=IST)
      WRITE (*, 100) IST, ALLOCATED(A), ALLOCATED(W)
      ALLOCATE (A(2,5))
      A(2,5) = 7.25D0
      WRITE (*, 200) A(2,5)
      DO 40 I = 1, 3
        CALL WORKER(I, J)
        WRITE (*, 300) J
   40 CONTINUE
  100 FORMAT (1X, I3, 2L3)
  200 FORMAT (1X, 6F8.2)
  300 FORMAT (1X, 8I5)
      END
      SUBROUTINE SHOW(A, M, N)
      INTEGER M, N, I
      DOUBLE PRECISION A(M, N)
      WRITE (*, '(1X,4F8.1)') (A(I,N), I = 1, M), A(1,1)
      END
      SUBROUTINE WORKER(K, ISUM)
      INTEGER K, ISUM, I
      INTEGER, ALLOCATABLE :: T(:)
      ALLOCATE (T(K*100))
      DO 10 I = 1, K*100
        T(I) = I
   10 CONTINUE
      ISUM = T(K*100) + T(1)
      END
