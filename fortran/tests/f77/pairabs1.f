C     A DOUBLE WHOSE LOW WORD IS ANOTHER'S: ABS(X) KEEPS X'S LOW WORD AND
C     CLEARS THE SIGN OF ITS HIGH ONE, AND MIN(Y,ABS(Y)) SELECTS INTO THE
C     SAME SHAPE.  THE ALLOCATOR ONCE GAVE ONE VALUE TWO PAIR PARTNERS AND
C     STORED THE HIGH WORD BEFORE IT WAS COMPUTED: Y - ABS(X) CAME OUT Y.
C     FOUND BY REGRESSION/FUZZ/FFUZZ.PY.  THE WRITES KEEP X AND Y LIVE.
      PROGRAM PAIRAB
      INTEGER IA(10), IB(10), K
      DOUBLE PRECISION X, Y, Z, T
      COMMON /CP/ IA
      DO 5 K = 1, 10
        IA(K) = K * 37 - 200
        IB(K) = 400 - K * 41
    5 CONTINUE
      X = -487.0D0
      Y = -150.53D0
      Z = 187.06D0
      WRITE (6, 902) X, Y, Z
      WRITE (6, 901) (IA(K), K = 1, 10), (IB(K), K = 1, 10)
      T = Y - ABS(X) + MIN(Y, ABS(Y))
      Y = T - AINT(T / 997.0D0) * 997.0D0
      WRITE (6, 902) X, Y, Z
      IF (Y .NE. -788.06D0) STOP 1
      STOP 0
  901 FORMAT (1X, 10I5)
  902 FORMAT (1X, 3E26.17E3)
      END
