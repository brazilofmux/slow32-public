C     FORTRAN 90 CEILING, FLOOR AND EXPONENT, REAL AND DOUBLE PRECISION:
C     NEGATIVES, EXACT INTEGERS, ZERO (EXPONENT 0), A SMALL AND A HUGE ONE.
      PROGRAM F90CE1
      REAL R(6)
      DOUBLE PRECISION D(6)
      INTEGER I
      DATA R /2.5, -2.5, 3.0, -3.0, 0.0, 1.0E-3/
      DATA D /2.5D0, -2.5D0, 3.0D0, -3.0D0, 0.0D0, 1.0D300/
      DO 10 I = 1, 5
        WRITE (*, 100) CEILING(R(I)), FLOOR(R(I)), CEILING(D(I)),
     &    FLOOR(D(I)), EXPONENT(R(I)), EXPONENT(D(I))
   10 CONTINUE
      WRITE (*, 100) EXPONENT(R(6)), EXPONENT(D(6)), CEILING(0.1),
     &  FLOOR(-0.1D0)
  100 FORMAT (1X, 6I6)
      END
