C     A REAL CONSTANT IS SINGLE PRECISION WHEREVER IT GOES: PARAMETER (D =
C     1.0/3.0) GIVES A DOUBLE PRECISION D THE REAL THIRD WIDENED, AND DATA
C     D /0.1/ THE REAL 0.1 WIDENED; R*3 IN A CONSTANT EXPRESSION ROUNDS AS
C     REAL ARITHMETIC DOES.  THE EVALUATOR HAD DONE IT ALL IN DOUBLE.
      PROGRAM CXRND1
      DOUBLE PRECISION D1, D2, D3, D4, D5
      REAL R1
      COMPLEX*16 A, B, C, E
      PARAMETER (D1 = 1.0/3.0, D2 = 1.0D0/3.0, R1 = 1.0/3.0)
      PARAMETER (D3 = R1 * 3, D4 = 0.1)
      PARAMETER (B = (0.1D0, 0.2))
      DATA D5 /0.1/, C /(0.3, 0.4D0)/, E /0.1/
      WRITE (*, 100) D1, D2
      WRITE (*, 100) DBLE(R1), D3
      WRITE (*, 100) D4, D5
      A = (0.1D0, 0.2)
      WRITE (*, 100) DREAL(A), DIMAG(A)
      WRITE (*, 100) DREAL(B), DIMAG(B)
      WRITE (*, 100) DREAL(C), DIMAG(C)
      WRITE (*, 100) DREAL(E), DIMAG(E)
  100 FORMAT (2F22.17)
      END
