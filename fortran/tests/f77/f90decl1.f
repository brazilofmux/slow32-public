C     FORTRAN 90 DECLARATIONS IN FIXED FORM: TYPE [, ATTRIBUTE]... :: ENTITY
C     [= VALUE] -- PARAMETER (WITH AN EXPRESSION OF ONE), DIMENSION BESIDE
C     A NAME'S OWN SHAPE, SAVE, EXTERNAL, INTENT; CHARACTER(LEN=N),
C     CHARACTER(N) AND CHARACTER*N, PARAMETER; AN INITIAL VALUE ON A SCALAR
C     AND BROADCAST TO AN ARRAY, AND A SAVED COUNTER.
      PROGRAM F90DC1
      INTEGER, PARAMETER :: N = 3, M = N*2
      DOUBLE PRECISION, PARAMETER :: HALF = 0.5D0
      CHARACTER(LEN=8) :: S = 'abc'
      CHARACTER(5) T
      CHARACTER*6, PARAMETER :: P = 'xyz'
      INTEGER, DIMENSION(N) :: K, L(2)
      INTEGER :: J, ICNT = 7
      REAL, SAVE :: R = 1.5
      INTEGER, EXTERNAL :: IDBL
      INTEGER :: Z(4) = 9
      DO 10 J = 1, N
        K(J) = J * M
   10 CONTINUE
      L(1) = 1
      L(2) = 2
      T = 'hello'
      WRITE (*, 100) K, L, ICNT, IDBL(4), Z
      WRITE (*, 200) HALF, R
      WRITE (*, 300) S, T, P
      CALL SUB(K)
  100 FORMAT (1X, 11I4)
  200 FORMAT (1X, 2F8.3)
  300 FORMAT (1X, '[', A, '][', A, '][', A, ']')
      END
      INTEGER FUNCTION IDBL(I)
      INTEGER, INTENT(IN) :: I
      IDBL = 2 * I
      END
      SUBROUTINE SUB(K)
      INTEGER, INTENT(INOUT) :: K(*)
      INTEGER, SAVE :: NCALL = 0
      NCALL = NCALL + 1
      WRITE (*, '(1X,2I4)') K(1), NCALL
      END
