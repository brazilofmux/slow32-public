C     A STORE TO LA(1) WHOSE ADDRESS IS (LA+4)-4: INSTRUCTION SELECTION
C     TAKES THE +4 INTO THE -4 AS A FRAME ADDRESS AND DELETES IT, AND THE
C     WALK THAT FOLDS AN ADDRESS INTO A STORE'S DISPLACEMENT WENT ON INTO
C     THE DELETED ONE, WHICH HAS NO REGISTER: THE STORE WENT TO -4.  THE
C     CALL TO INDEX AND THE VALUES LIVE ACROSS IT ARE WHAT LEAVES IT THERE.
C     FOUND BY REGRESSION/FUZZ/FFUZZ.PY.
      INTEGER FUNCTION KFN(N1, N2)
      INTEGER N1, N2, I1, I3, I4, I6, J, LA(10)
      INTEGER KC1, KC2
      REAL R
      CHARACTER*8 S
      COMMON /CK/ KC1, KC2
      I1 = -612
      I3 = 433
      I4 = 251
      I6 = 588
      R = -19.75
      S = 'QWERTY7Z'
      DO 9 J = 1, 10
        LA(J) = MOD(J * 307, 1499) - 700
    9 CONTINUE
      LA(1) = MOD((LA(1 + MOD(ABS(MAX(I1, KC1)), 10))
     &  - LA(1 + MOD(ABS(MAX(N1, I1)), 10)))
     &  + (INT(R) + INDEX(S(8:8), 'Z9')), 32749)
      KFN = MOD(I6 * I1 - MIN(MIN(I1, I3, I1), ISIGN(KC2, I4), KC2)
     &  * LA(2), 32749) + LA(1) + N2
      END
      PROGRAM FOLDB
      INTEGER KFN, K, KC1, KC2
      COMMON /CK/ KC1, KC2
      KC1 = 45
      KC2 = -3001
      K = KFN(6, 2)
      WRITE (6, 901) K
  901 FORMAT (1X, I8)
      IF (K .NE. -28784) STOP 1
      STOP 0
      END
