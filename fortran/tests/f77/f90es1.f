C     FORTRAN 90 ES AND EN EDITING: ES ONE NONZERO DIGIT AHEAD OF THE POINT,
C     EN AN EXPONENT THAT IS A MULTIPLE OF 3 -- ROUNDING THAT CARRIES TO THE
C     NEXT POWER OF TEN (999.95, 99999.5, .0999999), ZERO, NEGATIVES, EE,
C     SP AND SS, A REAL ITEM, AND ES ON INPUT.
      PROGRAM F90ES1
      DOUBLE PRECISION V(9), X
      REAL R
      INTEGER I
      CHARACTER*20 LINE
      DATA V /12345.678D0, -0.00123D0, 0.0D0, 999.95D0, 1.0D0,
     &  0.5D-10, 99999.5D0, -7.0D20, 0.0999999D0/
      DO 10 I = 1, 9
        WRITE (*, 100) V(I), V(I), V(I)
   10 CONTINUE
      R = 3.14159
      WRITE (*, 200) R, R, -R
      LINE = '  1.5E+02'
      READ (LINE, '(ES12.3)') X
      WRITE (*, '(1X,F10.3)') X
  100 FORMAT (1X, ES14.4, EN14.3, ES16.6E3)
  200 FORMAT (1X, SP, ES12.4, EN12.2, SS, ES12.4)
      END
