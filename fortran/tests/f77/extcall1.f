C     REFERENCES THE WAY LAPACK MAKES THEM.  F(G(...)) WITH G EXTERNAL:
C     THE INNER REFERENCE AS AN ACTUAL ARGUMENT WAS TAKEN FOR VARIABLE G,
C     ITS ADDRESS PASSED AND (...) LEFT UNPARSED -- "EXPECTED ) AFTER
C     ARGUMENTS" (DLAPY2(DNRM2(...), DNRM2(...)) IN DGEEV).  AND UNDER
C     IMPLICIT NONE, EXTERNAL XERBLA AND INTRINSIC ABS WERE REFUSED FOR
C     WANT OF A TYPE NEITHER NEEDS.  A CHARACTER SUBSTRING ACTUAL STAYS
C     A SUBSTRING.
      PROGRAM EXTCL1
      IMPLICIT NONE
      DOUBLE PRECISION V(4,2), R, HYP, SNRM
      INTEGER I, K
      CHARACTER*10 S
      INTEGER LENOF
      EXTERNAL HYP, SNRM, REPORT, APPLY, LENOF
      INTRINSIC ABS, SQRT
      DO 10 I = 1, 4
        V(I,1) = DBLE(I)
        V(I,2) = DBLE(5 - I) * 0.5D0
   10 CONTINUE
      R = HYP(SNRM(4, V(1,1), 1), SNRM(4, V(1,2), 1))
      WRITE (*, 100) R
      R = 1.0D0 / HYP(SNRM(2, V(3,1), 1), 3.0D0)
      WRITE (*, 100) R
      K = ABS(-7)
      CALL REPORT(K)
      S = 'ABCDEFGHIJ'
      CALL APPLY(REPORT, LENOF(S(3:7)))
  100 FORMAT (F14.8)
      END
      DOUBLE PRECISION FUNCTION HYP(A, B)
      DOUBLE PRECISION A, B
      HYP = SQRT(A * A + B * B)
      END
      DOUBLE PRECISION FUNCTION SNRM(N, X, INC)
      INTEGER N, INC, I
      DOUBLE PRECISION X(*)
      SNRM = 0.0D0
      DO 20 I = 1, N, INC
        SNRM = SNRM + X(I) * X(I)
   20 CONTINUE
      SNRM = SQRT(SNRM)
      END
      SUBROUTINE REPORT(K)
      INTEGER K
      WRITE (*, 200) K
  200 FORMAT (I6)
      END
      SUBROUTINE APPLY(P, K)
      IMPLICIT NONE
      INTEGER K
      EXTERNAL P
      CALL P(K)
      END
      INTEGER FUNCTION LENOF(C)
      CHARACTER*(*) C
      LENOF = LEN(C) * 100 + ICHAR(C(1:1))
      END
