C     FORTRAN 90 UNIT ENDS: END PROGRAM NAME, END FUNCTION NAME, END
C     SUBROUTINE; AND :: AFTER EXTERNAL, INTRINSIC AND SAVE.
      PROGRAM F90EN1
      INTEGER K, IDBL
      EXTERNAL :: IDBL, SHOW
      INTRINSIC :: MOD
      K = IDBL(21)
      CALL SHOW(K)
      CALL SHOW(MOD(K, 5))
      END PROGRAM F90EN1
      INTEGER FUNCTION IDBL(I)
      INTEGER I
      INTEGER, SAVE :: N = 0
      SAVE :: M
      INTEGER M
      DATA M /5/
      IDBL = 2 * I + N + M
      END FUNCTION IDBL
      SUBROUTINE SHOW(K)
      INTEGER K
      WRITE (*, '(1X,I6)') K
      END SUBROUTINE
