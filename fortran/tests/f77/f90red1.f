C     FORTRAN 90 MAXLOC MINLOC MAXVAL MINVAL OF A RANK-1 ARRAY OR SECTION
C     ([DIM=]1): LAPACK'S MAXLOC(WORK(1:N),1) AND MAXVAL(S(I:J)), A STRIDE,
C     EMPTY SECTIONS (-HUGE, +HUGE, LOCATION 0), AND NANS IN LIBGFORTRAN'S
C     ORDER (LOCATION 1 UNTIL A NUMBER IS FOUND).
      PROGRAM F90RD1
      DOUBLE PRECISION WORK(8), EMIN, D0
      REAL R(5), ZR
      INTEGER K(6), I, N, PVT, ITEMP
      DATA WORK /3.0D0, -1.0D0, 7.5D0, 7.5D0, 2.0D0, -9.0D0, 7.0D0,
     &  0.5D0/
      DATA R /1.5, -2.0, 4.0, 4.0, -2.0/
      DATA K /3, 9, -4, 9, 0, -4/
      N = 6
      PVT = MAXLOC(WORK(1:N), 1)
      ITEMP = MAXLOC(WORK((N-3):(2*N-6)), 1)
      WRITE (*, 100) PVT, ITEMP, MINLOC(WORK(2:8), DIM=1),
     &  MAXLOC(K, 1), MINLOC(K, 1), MAXLOC(R(2:5:2), 1)
      EMIN = ABS(MAXVAL(WORK(4:7)))
      WRITE (*, 200) EMIN, MINVAL(WORK), MAXVAL(WORK(3:1)),
     &  DBLE(MAXVAL(R)), DBLE(MINVAL(R(2:3)))
      WRITE (*, 100) MAXVAL(K), MINVAL(K(1:3)), MAXLOC(K(4:3), 1)
      ZR = 0.0
      D0 = 0.0D0
      WORK(1) = D0 / D0
      WORK(2) = D0 / D0
      R(1) = ZR / ZR
      WRITE (*, 100) MAXLOC(WORK(1:2), 1), MAXLOC(WORK(1:4), 1),
     &  MINLOC(R, 1)
  100 FORMAT (1X, 6I6)
  200 FORMAT (1X, 5E14.5)
      END
