C     AN ENTRY TYPED BY A TYPE STATEMENT BEFORE THE ENTRY STATEMENT: E2
C     WAS TAKEN AS REAL BY ITS INITIAL LETTER, AND EVERY REFERENCE TO IT
C     REFUSED ("E2 IS DOUBLE PRECISION HERE BUT REAL WHERE IT IS DEFINED").
C     ONE DECLARED AFTER ITS ENTRY STATEMENT WAS ALWAYS RIGHT.
      PROGRAM ENTTY1
      DOUBLE PRECISION E2, F, A
      A = 1.5D0
      WRITE (*, '(2F10.4)') F(A), E2(A)
      END
      DOUBLE PRECISION FUNCTION F(X)
      DOUBLE PRECISION X, E2
      F = X * 2
      RETURN
      ENTRY E2(X)
      E2 = X + 10
      END
