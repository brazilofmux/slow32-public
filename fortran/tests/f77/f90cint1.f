C     INTRINSICS IN A CONSTANT EXPRESSION (FORTRAN 90 INITIALIZATION
C     EXPRESSIONS): HUGE TINY EPSILON BY THE ARGUMENT'S TYPE, DCMPLX
C     CMPLX, MAX MIN MOD, INT NINT DBLE ABS -- LAPACK'S PARAMETER (HUGENUM =
C     HUGE(ZERO)) AND (CZERO = DCMPLX(0.0D0, 0.0D0)).
      PROGRAM F90CI1
      DOUBLE PRECISION ZERO, HUGENUM, EPS, TINYN
      PARAMETER (ZERO = 0.0D0, HUGENUM = HUGE(ZERO))
      PARAMETER (EPS = EPSILON(ZERO))
      PARAMETER (TINYN = TINY(ZERO))
      REAL RH
      PARAMETER (RH = HUGE(1.0))
      COMPLEX*16 CZERO, CONE
      PARAMETER (CZERO = DCMPLX(0.0D0, 0.0D0))
      PARAMETER (CONE = DCMPLX(1.0D0, 2.5D0))
      COMPLEX C1
      PARAMETER (C1 = CMPLX(1.5, -0.5))
      INTEGER IH, M1, M2, M3, I1, I2
      PARAMETER (IH = HUGE(1), M1 = MAX(3, 7, 2))
      PARAMETER (M2 = MIN(4, -1), M3 = MOD(17, 5))
      PARAMETER (I1 = INT(2.7), I2 = NINT(-2.5))
      DOUBLE PRECISION D1, D2
      PARAMETER (D1 = DBLE(0.1), D2 = ABS(-3.25D0))
      WRITE (*, 100) HUGENUM, EPS, TINYN, DBLE(RH)
      WRITE (*, 100) DREAL(CZERO), DIMAG(CONE), DBLE(REAL(C1)),
     &  DBLE(AIMAG(C1))
      WRITE (*, 200) IH, M1, M2, M3, I1, I2
      WRITE (*, 100) D1, D2
  100 FORMAT (1X, 4E25.16E3)
  200 FORMAT (1X, 6I12)
      END
