C     COMPLEX*16 AND DOUBLE COMPLEX: DECLARATIONS, SCALARS AND ARRAYS,
C     DCMPLX, CONVERSION TO AND FROM EVERY NUMERIC TYPE, AND THE PARTS:
C     DREAL/DBLE/REAL AND DIMAG/AIMAG GIVE DOUBLE PRECISION OF ONE, AS
C     GFORTRAN HAS THEM; DCONJG/CONJG A COMPLEX*16.  F77 REFUSED THE TYPE
C     UNTIL 2026-11-08 (DOCS/PLANS/FORTRAN77.MD, "COMPLEX*16").
      PROGRAM DCPLX1
      COMPLEX*16 A, B(3)
      DOUBLE COMPLEX C
      COMPLEX S
      DOUBLE PRECISION D
      REAL R
      INTEGER I, K
      A = DCMPLX(1.5D0, -2.25D0)
      C = A
      S = (3.0, 4.0)
      DO 10 K = 1, 3
        B(K) = DCMPLX(DBLE(K), DBLE(K) * 0.5D0)
   10 CONTINUE
      WRITE (*, 100) DREAL(A), DIMAG(A)
      WRITE (*, 100) DBLE(C), AIMAG(C)
      WRITE (*, 100) DREAL(B(2)), DIMAG(B(3))
      C = S
      WRITE (*, 100) DREAL(C), DIMAG(C)
      C = 7
      WRITE (*, 100) DREAL(C), DIMAG(C)
      C = 0.1D0
      WRITE (*, 100) DREAL(C), DIMAG(C)
      C = DCONJG(A)
      WRITE (*, 100) DREAL(C), DIMAG(C)
      C = CONJG(B(1))
      WRITE (*, 100) DREAL(C), DIMAG(C)
      D = A
      R = A
      I = A
      S = A
      WRITE (*, 100) D, DBLE(R)
      WRITE (*, 200) I
      WRITE (*, 100) DBLE(REAL(S)), DBLE(AIMAG(S))
      C = DCMPLX(S)
      WRITE (*, 100) DREAL(C), DIMAG(C)
      C = DCMPLX(2)
      WRITE (*, 100) DREAL(C), DIMAG(C)
      B(3) = B(1)
      WRITE (*, 100) DREAL(B(3)), DIMAG(B(3))
  100 FORMAT (2F22.15)
  200 FORMAT (I6)
      END
